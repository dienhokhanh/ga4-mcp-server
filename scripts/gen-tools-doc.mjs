// Regenerates docs/tools.md from the tool schemas the server actually registers.
// Usage: npm run build && npm run docs
import fs from "node:fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { createClients } from "../dist/clients.js";
import { loadConfig } from "../dist/config.js";
import { createServer } from "../dist/server.js";

const server = createServer({ ...loadConfig({}), enableWrites: true }, createClients({ scopes: [] }));
const client = new Client({ name: "docs", version: "0" });
const [a, b] = InMemoryTransport.createLinkedPair();
await Promise.all([server.connect(b), client.connect(a)]);

const { tools } = await client.listTools();
const { prompts } = await client.listPrompts();

function typeOf(schema) {
  if (!schema) return "any";
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(" \\| ");
  if (schema.type === "array") return `${typeOf(schema.items)}[]`;
  if (schema.type === "object") return "object";
  return schema.type ?? "any";
}

const esc = (s) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, "<br>");

let md = `# Tool reference\n\n<!-- Generated by scripts/gen-tools-doc.mjs — do not edit by hand. -->\n\n`;
md += `Every tool accepts \`property\` as a numeric ID, \`properties/ID\` or display name; it can be omitted when \`GA4_DEFAULT_PROPERTY\` is set.\n\n`;

for (const tool of tools) {
  const write = tool.annotations?.readOnlyHint === false;
  md += `## \`${tool.name}\`${write ? " ✍️ _(write — requires `GA4_MCP_ENABLE_WRITES=true`)_" : ""}\n\n${tool.description}\n\n`;
  const props = Object.entries(tool.inputSchema.properties ?? {});
  if (props.length) {
    const required = new Set(tool.inputSchema.required ?? []);
    md += `| Parameter | Type | Required | Description |\n|---|---|---|---|\n`;
    for (const [name, schema] of props) {
      const def = schema.default !== undefined ? ` Default: \`${JSON.stringify(schema.default)}\`.` : "";
      md += `| \`${name}\` | ${typeOf(schema)} | ${required.has(name) ? "yes" : ""} | ${esc(schema.description)}${def} |\n`;
    }
    md += "\n";
  }
}

md += `# Prompts\n\n`;
for (const p of prompts) {
  const args = (p.arguments ?? []).map((a) => `\`${a.name}\``).join(", ");
  md += `- **\`${p.name}\`**: ${p.description}${args ? ` Arguments: ${args}.` : ""}\n`;
}

fs.writeFileSync(new URL("../docs/tools.md", import.meta.url), md);
console.log(`Wrote docs/tools.md (${tools.length} tools, ${prompts.length} prompts)`);
await client.close();
